"""Перевод цен DMarket между центами и долларами.

Функции повторяют выражения, которые уже стоят в коде бота:
    cents_to_usd(x) == float(x) / 100.0
    usd_to_cents(x) == int(round(x * 100))
round() в Python округляет половину к чётному (12.5 -> 12), как и текущий код.
Какой эндпоинт отдаёт центы, а какой доллары, здесь не решается: это дело вызывающего.
"""


def cents_to_usd(cents: int | float | str) -> float:
    """Центы (число или строка) -> доллары."""
    return float(cents) / 100.0


def usd_to_cents(usd: float) -> int:
    """Доллары -> целые центы, с округлением, а не отбрасыванием дробной части."""
    return int(round(usd * 100))
